def t(key, language=None, fallback=None):
    """دالة مختصرة للترجمة

    Args:
        key: مفتاح الترجمة
        language: اللغة (اختياري، إذا لم يُعط سيتم استخدام اللغة الحالية)
        fallback: القيمة البديلة إذا لم يُعثر على الترجمة
    """
    if language:
        if key in TRANSLATIONS:
            return TRANSLATIONS[key].get(language, fallback or key)
        return fallback or key
    return translator.get(key, fallback)


